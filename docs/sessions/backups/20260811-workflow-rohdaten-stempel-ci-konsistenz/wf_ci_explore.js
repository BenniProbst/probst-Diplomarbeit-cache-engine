const roh = await pipeline(
  SCHNITTE,
  (s) => agent(s.prompt, { label: 'ci:' + s.key, phase: 'Explore', schema: FUND_SCHEMA, model: 'sonnet' }),
  (r, s) => {
    if (!r || !r.funde || r.funde.length === 0) return { schnitt: s.key, funde: [], geprueft: [] }
    const tragend = r.funde.filter(f => f.gewicht === 'OWNER-WORT' || f.gewicht === 'CODE-OBJEKT' || f.blocker === true).slice(0, 6)
    if (tragend.length === 0) return { schnitt: s.key, funde: r.funde, geprueft: [], gegenproben: r.gegenproben, nichtfunde: r.nichtfunde }
    return parallel(tragend.map(f => () =>
      agent(
        [
          'ADVERSARISCHE GEGENPROBE. Versuche den folgenden Befund zu WIDERLEGEN.',
          '',
          'BEFUND:  ' + f.aussage,
          'ZITAT:   ' + f.zitat,
          'QUELLE:  ' + f.quelle,
          'GEWICHT: ' + f.gewicht,
          'BLOCKER: ' + (f.blocker === true ? 'ja' : 'nein'),
          '',
          'Pruefe SELBST an der Quelle:',
          '  1. Existiert die Quelle, existiert die Zeile?',
          '  2. Steht das Zitat WOERTLICH dort -- oder geglaettet, gekuerzt, umgestellt?',
          '  3. Traegt das Zitat die Aussage, oder etwas Benachbartes?',
          '  4. Noch GUELTIG, oder spaeter widerrufen? Ledger-Nachtraege stehen OBEN, spaeter',
          '     schlaegt frueher. Der Wellenplan traegt Korrektur-Einschuebe, die seine eigenen',
          '     Abschnitte ueberholen.',
          '  5. Bei BLOCKER: besteht er HEUTE noch? Am Objekt messen. Ein gefallener Blocker ist',
          '     eine wertvolle Entlastung -- widerlegt ihn ruhig.',
          '  6. Bei CODE-OBJEKT: heutigen Stand messen. ce = /home/comdare/wt-ce-warn-libs',
          '     (670483c0), super = /home/comdare/wt-super-landung.',
          '',
          'WERKZEUG: /usr/bin/grep ABSOLUT. grep -v /build frisst /builder/ -- beide Schraegstriche.',
          'Jeder Nichtfund braucht Gegenprobe mit Trefferzahl. Bei generierten CI-Jobs beweist',
          'Abwesenheit im eingecheckten YAML nichts.',
          '',
          'Sei im Zweifel SKEPTISCH: widerlegt=true, wenn du die Quelle nicht selbst bestaetigen',
          'konntest.',
        ].join('\n'),
        {
          label: 'verify:' + s.key,
          phase: 'Verify',
          model: 'sonnet',
          schema: {
            type: 'object',
            additionalProperties: false,
            required: ['widerlegt', 'begruendung'],
            properties: {
              widerlegt: { type: 'boolean' },
              begruendung: { type: 'string' },
              korrigiertes_zitat: { type: 'string' },
              besteht_heute_noch: { type: 'boolean', description: 'nur bei Blockern gesetzt' },
            },
          },
        }
      ).then(v => ({ fund: f, verdikt: v }))
    )).then(geprueft => ({ schnitt: s.key, funde: r.funde, geprueft: geprueft.filter(Boolean), gegenproben: r.gegenproben, nichtfunde: r.nichtfunde }))
  }
)

const alle = roh.filter(Boolean)
const bestaetigt = alle.flatMap(r => (r.geprueft || []).filter(g => g.verdikt && !g.verdikt.widerlegt).map(g => ({ ...g.fund, schnitt: r.schnitt, besteht_heute_noch: g.verdikt.besteht_heute_noch })))
const gefallen = alle.flatMap(r => (r.geprueft || []).filter(g => g.verdikt && g.verdikt.widerlegt).map(g => ({ ...g.fund, schnitt: r.schnitt, grund: g.verdikt.begruendung })))
const blocker = bestaetigt.filter(f => f.blocker === true && f.besteht_heute_noch !== false)

log('CI-Explore durch: ' + bestaetigt.length + ' bestaetigt, ' + gefallen.length + ' gefallen, ' + blocker.length + ' Blocker bestehen heute noch')

