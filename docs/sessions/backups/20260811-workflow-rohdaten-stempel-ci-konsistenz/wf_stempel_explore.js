          '  2. Steht das Zitat dort WOERTLICH -- oder geglaettet, gekuerzt, umgestellt?',
          '  3. Traegt das Zitat die Aussage -- oder sagt es etwas Benachbartes?',
          '  4. Ist es noch GUELTIG oder spaeter widerrufen? Ledger-Nachtraege stehen OBEN,',
          '     ein spaeterer Nachtrag schlaegt einen frueheren.',
          '  5. Bei CODE-OBJEKT: miss den heutigen Stand selbst nach.',
          '     ce = /home/comdare/wt-ce-warn-libs (670483c0), super = /home/comdare/wt-super-landung.',
