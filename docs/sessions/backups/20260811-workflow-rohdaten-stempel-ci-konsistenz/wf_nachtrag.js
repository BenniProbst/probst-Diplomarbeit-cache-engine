          '  2. Traegt der Beleg die Aussage -- oder etwas Benachbartes?',
          '  3. Noch gueltig, oder spaeter ueberholt? (Owner: "Neu schlaegt grundsaetzlich alte',
          '     Aussage." Ein juengerer Owner-Satz schlaegt einen aelteren.)',
          '  4. Bei CODE-OBJEKT: heutigen Stand messen, ce = /home/comdare/wt-ce-warn-libs (670483c0).',
          '     Unterscheide AUFRUF von include/Kommentar/Gate.',
